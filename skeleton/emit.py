def esc(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')


def one_line(s):
    return re.sub(r'\s+', ' ', s or '').strip()


def literal_value(init, ref):
    if not init:
        return None
    s = init.strip()
    if s.startswith('{') and s.endswith('}'):
        s = s[1:-1].strip()
    if ref.kind == 'b':
        if ref.name == 'bool' and s in ('true', 'false'):
            return s
        if ref.name in ('u8', 'u16', 'u32', 'u64', 'i8', 'i16', 'i32', 'i64', 'usize', 'isize'):
            m = re.fullmatch(r'(-?)\s*(0x[0-9a-fA-F]+|\d+)[uUlL]*', s)
            if m:
                v = m.group(2)
                if v.startswith('0x'):
                    v = '0x' + v[2:].lower()
                if m.group(1) and ref.name.startswith('u'):
                    return None
                return (m.group(1) + v) if m.group(1) else v
        if ref.name in ('f32', 'f64'):
            m = re.fullmatch(r'(-?)\s*(\d+\.\d*(?:[eE][-+]?\d+)?|\d+[eE][-+]?\d+)[fF]?', s)
            if m:
                v = m.group(2)
                if v.endswith('.'):
                    v += '0'
                return m.group(1) + v
    return None
