BAR = '#' + '=' * 94
MARK_WIDTH = 97


def header_box(title, desc_lines):
    out = [BAR, '#', f'#   {title}', '#', '#   DESCRIPTION:']
    for line in desc_lines:
        out.append('#       ' + line if line else '#')
    out += ['#', BAR, '']
    return out


def mark(name):
    s = f'# mark: {name} '
    return s + '=' * max(4, MARK_WIDTH - len(s))


def wrap_desc(text, width=86):
    words = text.split()
    lines, cur = [], ''
    for w in words:
        if len(cur) + len(w) + 1 > width:
            lines.append(cur)
            cur = w
        else:
            cur = (cur + ' ' + w).strip()
    if cur:
        lines.append(cur)
    return lines


PACKAGE_ROOT = {p: 'luce_browser_' + p for p in S.PACKAGES}


def fragment_path_for_file(module, path):
    """Directory (relative to the module dir) and stem for a donor file's types fragment."""
    stem = S.stem(path)
    base = N.snake(os.path.basename(stem))
    if module == 'web':
        rel = stem
        for prefix in ('Libraries/LibWeb/', 'Build/Libraries/LibWeb/'):
            if rel.startswith(prefix):
                sub = os.path.dirname(rel[len(prefix):])
                subdir = '/'.join(N.snake(p) for p in sub.split('/') if p)
                if rel.startswith('Build/'):
                    subdir = 'generated/' + subdir if subdir else 'generated'
                return subdir, base
        lib = N.snake(lib_of(path) or 'external')
        return 'external/' + lib, base
    if path.startswith('Build/'):
        return '', 'generated_' + base
    return '', base


class Emitter:
    def __init__(self, planner, namer, package, outdir):
        self.p = planner
        self.nm = namer
        self.package = package
        self.out = outdir
        self.modules = [m for m in S.MODULES if S.PACKAGE_OF[m] == package and m not in S.FOREIGN_MODULES]
        self.refs_used = collections.defaultdict(set)
        self.stats = collections.Counter()
        self.namemap = []
        self.extra_imports = collections.defaultdict(set)
        self.baseline = None   # baseline.Baseline of the ported package (class ids, names)

    # ---- rendering helpers --------------------------------------------------------------------
    def names_cb(self, module):
        def cb(key):
            d = self.p.decls[key]
            if d.module != module:
                self.refs_used[module].add(d.module)
            return d.module, d.name
        return cb

    def R(self, ref, module):
        return render(ref, module, self.names_cb(module))

    def qual(self, module, target_module, name):
        if target_module != module:
            self.refs_used[module].add(target_module)
            return f'{target_module}.{name}'
        return name

    def dname(self, key, module):
        d = self.p.decls[key]
        return self.qual(module, d.module, d.name)

    def visible_ref(self, ref, module):
        for key, bv in walk_refs(ref, True):
            d = self.p.decls.get(key)
            if d is None:
                return False
            if not self.p.visible(module, d.module):
                return False
        return True

    # ---- per module ----------------------------------------------------------------------------
    def emit(self):
        p = self.p
        for module in self.modules:
            self.emit_module(module)

    def emit_module(self, module):
        p = self.p
        frags = collections.OrderedDict()   # relpath -> dict(title, desc, blocks[(sortkey, lines)])

        def frag(rel, title, desc):
            f = frags.get(rel)
            if f is None:
                f = {'title': title, 'desc': desc, 'blocks': [], 'files': set()}
                frags[rel] = f
            return f

        decls = [d for d in p.decls.values() if d.module == module and d.kind != 'ovr']
        for d in decls:
            if d.kind in ('variant', 'traits'):
                rel = 'types_variants.lucb' if d.kind == 'variant' else 'types_traits.lucb'
                if module == 'web':
                    rel = 'generated/' + rel
                f = frag(rel, rel.split('/')[-1][:-5] + ' - ' + (
                    'Variant<...> instantiations as payload enums' if d.kind == 'variant' else
                    'hash traits of the key types of HashMap/HashTable instantiations'),
                    ['Generated by the skeleton generator (DESIGN.md §2.6): one declaration per distinct',
                     f'instantiation the phase-1 declarations use, at donor commit {PIN}.'])
                lines = self.emit_variant(d, module) if d.kind == 'variant' else self.emit_traits(d, module)
                f['blocks'].append(((d.name,), lines))
                continue
            path = d.file or ''
            sub, base = fragment_path_for_file(module, path) if path else ('', 'external')
            rel = (sub + '/' if sub else '') + 'types_' + base + '.lucb'
            f = frag(rel, 'types_' + base + ' - declarations of ' + (path or 'external declarations'), None)
            if path:
                f['files'].add(path)
            lines = self.emit_decl(d, module)
            if lines:
                f['blocks'].append(((d.line, d.q, str(d.key)), lines))
        for v, ref in p.var_tasks:
            key_mod = self.var_module(v, ref)
            if key_mod != module:
                continue
            sub, base = fragment_path_for_file(module, v['file'])
            rel = (sub + '/' if sub else '') + 'types_' + base + '.lucb'
            f = frag(rel, 'types_' + base + ' - declarations of ' + v['file'], None)
            f['files'].add(v['file'])
            f['blocks'].append(((v['line'], v['q'], v['usr']), self.emit_var(v, ref, module)))
        # functions by region
        funcs = [F for F in p.funcs if F.module == module]
        funcs.sort(key=lambda F: (self.fn_sort_file(F), self.fn_line(F), F.name))
        for F in funcs:
            if F.region:
                rid, rname, _ = F.region
                rel = f'stub_{rid}_{rname}.lucb'
                title = f'stub_{rid}_{rname} - typed stubs of region {rid} ({rname})'
            else:
                rel = 'stub_closure.lucb'
                title = 'stub_closure - stubs of virtual functions of classes outside the phase-1 files'
            if module == 'web':
                rel = 'stubs/' + rel
            f = frag(rel, title, None)
            f['files'].add(self.fn_file(F))
            f['blocks'].append(((self.fn_sort_file(F), self.fn_line(F), F.name), self.emit_func(F, module)))
        self.write_module(module, frags)

    def fn_file(self, F):
        d = self.p.defs.get(F.fn['usr'])
        return d['file'] if d and d.get('file') else F.fn['file']

    def fn_line(self, F):
        """The line of the function's definition (its C++ order), else of its declaration."""
        d = self.p.defs.get(F.fn['usr'])
        return d['line'] if d and d.get('line') else F.fn['line']

    def fn_sort_file(self, F):
        return S.stem(self.fn_file(F))

    def var_module(self, v, ref):
        return v.get('_module') or 'web'

    # ---- declarations ---------------------------------------------------------------------------
    def emit_decl(self, d, module):
        if d.kind == 'record':
            return self.emit_record(d, module)
        if d.kind == 'opaque':
            return self.emit_opaque(d, module)
        if d.kind == 'enum':
            return self.emit_enum(d, module)
        if d.kind == 'tmpl':
            return self.emit_tmpl(d, module)
        if d.kind == 'opaque_tmpl':
            r = self.p.tmpl_by_usr[d.key[1]]
            params = [tpn(tp['n']) for tp in r['tparams'] if tp['k'] == 'type']
            self.namemap.append((d.q, module, d.name, self.loc(d), 'opaque generic'))
            return [f'## {d.q} ({self.loc(d)}): opaque in this phase.',
                    f'pub struct {d.name}' + (f'[{", ".join(params)}]' if params else '') + ':',
                    '    pub var opaque_: u8', '']
        if d.kind == 'inst':
            return self.emit_inst(d, module)
        return []

    def clean_q(self, q):
        return re.sub(r'\((unnamed|anonymous) (union|struct|enum|class)? ?at [^)]*\)', r'(anonymous \2)', q or '')

    def loc(self, d):
        return f'{d.file}:{d.line}' if d.file else 'generated'

    def emit_opaque(self, d, module):
        self.stats['opaque'] += 1
        self.namemap.append((d.q, module, d.name, self.loc(d), 'opaque'))
        return [f'## {d.q or d.name} ({self.loc(d)}): opaque in this phase (not in the phase-{S.PHASE} closure).',
                f'pub struct {d.name}:', '    pub var opaque_: u8', '']

    def field_lines(self, fields, module, owner_name, taken, owner_q=''):
        out = []
        idx = 0
        self.last_fields = []
        for fd, ref in fields:
            cut = S.FIELD_CUTS.get((owner_q, fd['n']))
            if cut:
                for fname, ftype, mods in cut:
                    for m in mods:
                        if m != module:
                            self.refs_used[module].add(m)
                    taken.add(fname)
                    out.append(f'    pub var {fname}: {ftype}  # retyped (DESIGN.md §4.1.3): '
                               + one_line(spelling_of(fd['t']))[:80] + f' {fd["n"]}')
                self.stats['retyped_fields'] += 1
                continue
            name = N.field_name(fd['n'] or f'unnamed_{idx}')
            idx += 1
            while name in taken:
                name += '_'
            taken.add(name)
            comment = ''
            if fd.get('bits'):
                if ref.kind == 'b' and ref.name == 'bool':
                    pass
                comment = f'  # bit-field : {fd["bits"]}'
            if has_unmapped(ref):
                ts = 'void*?'
                comment = '  # unmapped: ' + one_line('; '.join(unmapped_notes(ref)))[:120]
                self.stats['unmapped_fields'] += 1
            elif not self.visible_ref(ref, module):
                ts = 'void*?'
                comment = '  # cut (upward reference, DESIGN.md §4.1.3): ' + one_line(spelling_of(fd['t']))[:100]
                self.stats['cut_fields'] += 1
            else:
                ts = self.R(ref, module)
                self.last_fields.append((fd, name, ref))
            init = fd.get('init')
            if init and not comment:
                init = one_line(init)
                if len(init) > 60:
                    init = init[:57] + '...'
                comment = f'  # C++ default: {init}'
            out.append(f'    pub var {name}: {ts}{comment}')
        return out

    def emit_record(self, d, module):
        p = self.p
        usr = d.key[1]
        r = p.records[usr]
        self.stats['structs'] += 1
        lines = [mark(d.name), '']
        lines.append(f'## {self.clean_q(d.q)} ({self.loc(d)}).')
        self.namemap.append((self.clean_q(d.q), module, d.name, self.loc(d), 'struct'))
        poly = p.is_poly(usr)
        prim = p.primary(usr)
        is_root = poly and (prim is None or not p.is_poly(prim))
        conf = []
        body_methods = []
        taken = set()
        upcasts = []
        if poly:
            chain = []
            u = usr
            while u is not None and p.is_poly(u):
                chain.append(u)
                pu = p.primary(u)
                if pu is None or not p.is_poly(pu):
                    break
                u = pu
            for a in chain:
                ad = p.decls.get(('rec', a))
                if ad is None:
                    continue
                iname = self.qual(module, ad.module, 'Is' + ad.name)
                conf.append(iname)
                mname = N.snake(ad.name)
                upcasts.append(f'    func {mname}() -> {self.qual(module, ad.module, ad.name)}*: '
                               f'return ({self.qual(module, ad.module, ad.name)}*)&self')
                taken.add(mname)
        traits_k = p.traits_records.get(usr)
        if traits_k is not None and not has_unmapped(traits_k):
            conf.append(self.qual(module, 'ak', 'Traits') + '[' + self.R(traits_k, module) + ']')
        kw = 'union' if r['kind'] == 'union' else 'struct'
        head = f'pub {kw} {d.name}' + (': ' + ', '.join(conf) if conf and kw == 'struct' else '') + ':'
        lines.append(head)
        fields = []
        if is_root:
            fields.append(f'    pub var vtable: const {d.name}VTable*')
            fields.append('    pub var class_id: u16')
        bnames, taken = self.base_fields(usr)
        for role, t, bu, fname in bnames:
            if role in ('primary', 'mixin'):
                bd = p.decls[('rec', bu)]
                fields.append(f'    pub var {fname}: {self.qual(module, bd.module, bd.name)}'
                              + ('  # primary base' if role == 'primary' else '  # mixin base'))
            else:
                ref = p.tr.tr(t, {}, 'field')
                fields.append(f'    pub var {fname}: {self.R(ref, module)}  # base {spelling_of(t)}')
        fields += self.field_lines(d.info.get('fields', []), module, d.name, taken, d.q)
        own_fields = list(self.last_fields)
        if kw == 'union':
            fields = [f.replace('    pub var ', '    pub ', 1) for f in fields]
        if not fields:
            fields.append('    pub var empty_: u8' if kw == 'struct' else '    pub empty_: u8')
        lines += fields
        if traits_k is not None and not has_unmapped(traits_k) and kw == 'struct':
            ks = self.R(traits_k, module)
            kp = f'const ({ks})*' if ks.endswith('*') or ks.endswith('?') else f'const {ks}*'
            lines.append(f'    func hash_of(key: {kp}) -> u32: trap("unported: {d.q}::hash")')
            lines.append(f'    func equals(a: {kp}, b: {kp}) -> bool: trap("unported: {d.q}::equals")')
        if kw == 'struct':
            lines += upcasts
        lines.append('')
        if kw == 'struct':
            lines += self.init_fields(d, module, own_fields)
            lines += self.tree_iterators(d, module)
        if poly:
            lines += self.emit_poly(d, module, is_root)
        return lines

    def init_fields(self, d, module, fields):
        """<class>_init_fields: the C++ default member initializers that are not zero (§2.3)."""
        body = []
        for fd, name, ref in fields:
            init = one_line(fd.get('init') or '')
            if not init:
                continue
            v = init[1:-1].strip() if init.startswith('{') and init.endswith('}') else init
            if v in ('', '0', 'false', 'nullptr', '0.0', '0.0f', '0u', '0ul', 'nullptr_t'):
                continue
            lit = literal_value(init, ref)
            if lit is not None:
                if lit.strip('-') in ('0', '0.0', '0x0'):
                    continue
                body.append(f'    this.{name} = {lit}')
                continue
            if ref.kind == 'decl' and ref.key[0] == 'enum':
                case = self.enum_case(ref.key, v)
                if case is not None:
                    if case[1] != 0:
                        body.append(f'    this.{name} = {self.dname(ref.key, module)}.{case[0]}')
                    continue
            if ref.kind == 'b' and ref.name == 'bool' and v in ('true',):
                body.append(f'    this.{name} = true')
                continue
            body.append(f'    # {name}: C++ default {v[:90]} (not translated by the generator)')
        if not body:
            return []
        s = N.snake(d.name)
        name = f'{s}_init_fields'
        self.stats['init_fields'] += 1
        self.namemap.append((f'{self.clean_q(d.q)} [default member initializers]', module, name, self.loc(d),
                             'init fields'))
        if all(b.lstrip().startswith('#') for b in body):
            body.append('    return')
        return [f'## The non-zero default member initializers of {self.clean_q(d.q)}; the constructor runs them first.',
                f'pub func {name}(this: {d.name}*):'] + body + ['']

    def tree_iterators(self, d, module):
        """for-loop iterators over a TreeNode<T> tree (DESIGN.md §2.9), for the class embedding it."""
        p = self.p
        embeds = [t for role, t, bu in p.eff_bases(d.key[1]) if role == 'embed' and t.get('tq') == 'Web::TreeNode']
        if not embeds:
            return []
        args = embeds[0].get('args') or []
        if len(args) != 1 or args[0].get('usr') != d.key[1]:
            return []
        self.extra_imports[module].add('luce')
        n = d.name
        s = N.snake(n)
        self.stats['tree_iterators'] += 1
        for fn in (f'{s}_children', f'{s}_subtree', f'{s}_inclusive_subtree'):
            self.namemap.append((f'{self.clean_q(d.q)} [TreeNode iteration]', module, fn, self.loc(d), 'iterator'))
        return f'''## `for child in {s}_children(node)`: TreeNode<{d.q.split('::')[-1]}>::for_each_child as a loop (DESIGN.md §2.9).
pub struct {n}Children: luce.Iterable[{n}*, {n}ChildIterator]:
    pub var parent: {n}*

    func iterator() -> {n}ChildIterator:
        return {n}ChildIterator(next_node = self.parent.tree_node.m_first_child)

## The iterator of {n}Children: each child in order.
pub struct {n}ChildIterator: luce.Iterator[{n}*]:
    pub var next_node: {n}*?

    mutating func next() -> {n}*?:
        let node = self.next_node else return none
        self.next_node = node.tree_node.m_next_sibling
        return node

## The children of `node`, first to last.
pub func {s}_children(node: {n}*) -> {n}Children:
    return {n}Children(parent = node)

## `for n in {s}_subtree(node)`: for_each_in_subtree / for_each_in_inclusive_subtree as a loop, in
## pre-order; `skip_children()` on the iterator is TraversalDecision::SkipChildrenAndContinue.
pub struct {n}Subtree: luce.Iterable[{n}*, {n}SubtreeIterator]:
    pub var root: {n}*
    pub var inclusive: bool

    func iterator() -> {n}SubtreeIterator:
        return {n}SubtreeIterator(root = self.root, current = none, inclusive = self.inclusive, started = false,
            skip = false)

## The iterator of {n}Subtree (TreeNode<T>::next_in_pre_order with stay_within = the root).
pub struct {n}SubtreeIterator: luce.Iterator[{n}*]:
    pub var root: {n}*
    pub var current: {n}*?
    pub var inclusive: bool
    pub var started: bool
    pub var skip: bool

    mutating func next() -> {n}*?:
        if not self.started:
            self.started = true
            self.current = self.root
            if self.inclusive:
                return self.root
        let node = self.current else return none
        var next: {n}*? = none
        if not self.skip:
            next = node.tree_node.m_first_child
        self.skip = false
        if next == none:
            var walk: {n}*? = node
            while let at = walk:
                if at == self.root:
                    break
                if let sibling = at.tree_node.m_next_sibling:
                    next = sibling
                    break
                walk = at.tree_node.m_parent
        self.current = next
        return next

    ## Do not descend into the children of the node `next()` returned last.
    mutating func skip_children():
        self.skip = true

## The descendants of `node` in pre-order (not `node` itself).
pub func {s}_subtree(node: {n}*) -> {n}Subtree:
    return {n}Subtree(root = node, inclusive = false)

## `node` and its descendants in pre-order.
pub func {s}_inclusive_subtree(node: {n}*) -> {n}Subtree:
    return {n}Subtree(root = node, inclusive = true)
'''.split('\n')

    def enum_case(self, key, text):
        """(Luce case, value) for a C++ enumerator spelled `text` (`Type :: Invalid`, `Invalid`)."""
        e = self.p.enums.get(key[1])
        if e is None:
            return None
        m = re.fullmatch(r'(?:[A-Za-z_][A-Za-z0-9_]*\s*::\s*)*([A-Za-z_][A-Za-z0-9_]*)', text)
        if not m:
            return None
        cname = m.group(1)
        cmap = self.enum_cases(e)
        return cmap.get(cname)

    def enum_cases(self, e):
        """C++ enumerator -> (Luce case of its value, value), as emit_enum names them."""
        out = {}
        seen_names = set()
        seen_vals = {}
        for cname, val in e['cases']:
            n = N.safe(N.snake(cname))
            if n == 'none':
                n = 'none_'
            while n in seen_names:
                n += '_'
            if val in seen_vals:
                out[cname] = (seen_vals[val], val)
                continue
            seen_names.add(n)
            seen_vals[val] = n
            out[cname] = (n, val)
        return out

    def upcast_chain(self, usr):
        p = self.p
        chain = []
        u = usr
        while u is not None and p.is_poly(u):
            chain.append(u)
            pu = p.primary(u)
            if pu is None or not p.is_poly(pu):
                break
            u = pu
        return chain

    def base_fields(self, usr):
        """[(role, ser, base usr, field name)] of a record's embedded bases, and the member names taken."""
        cache = self.__dict__.setdefault('_base_fields', {})
        if usr in cache:
            return cache[usr]
        p = self.p
        taken = set()
        if p.is_poly(usr):
            for a in self.upcast_chain(usr):
                ad = p.decls.get(('rec', a))
                if ad is not None:
                    taken.add(N.snake(ad.name))
            prim = p.primary(usr)
            if prim is None or not p.is_poly(prim):
                taken |= {'vtable', 'class_id'}
        out = []
        for role, t, bu in p.eff_bases(usr):
            if role in ('primary', 'mixin'):
                fname = N.snake(p.records[bu]['q'].split('::')[-1])
            else:
                ref = p.tr.tr(t, {}, 'field')
                if has_unmapped(ref):
                    continue
                fname = N.snake(t.get('tq', 'base').split('::')[-1])
            fname = N.field_name(fname)
            while fname in taken:
                fname += '_base'
            taken.add(fname)
            out.append((role, t, bu, fname))
        cache[usr] = (out, set(taken))
        return out, set(taken)

    def mixin_offsets(self, usr):
        """{mixin field name: (declaring class usr, field name)} along the primary chain."""
        out = {}
        u = usr
        while u is not None:
            for role, t, bu, fname in self.base_fields(u)[0]:
                if role == 'mixin':
                    key = N.snake(self.p.records[bu]['q'].split('::')[-1])
                    out.setdefault(key, (u, fname, bu))
            u = self.p.primary(u)
        return out

    # ---- polymorphism ---------------------------------------------------------------------------
    def emit_poly(self, d, module, is_root):
        p = self.p
        usr = d.key[1]
        vi = p.vinfo.get(usr, {'slots': [], 'overrides': []})
        out = []
        # interface
        out.append(f'## Upcast to {d.q} (implemented by every struct in its hierarchy).')
        out.append(f'pub interface Is{d.name}:')
        out.append(f'    func {N.snake(d.name)}() -> {d.name}*')
        out.append('')
        # vtable struct
        out.append(f'## Virtual functions introduced by {d.q}.')
        out.append(f'pub struct {d.name}VTable:')
        prim = p.primary(usr)
        if prim is not None and p.is_poly(prim):
            pd = p.decls[('rec', prim)]
            out.append(f'    pub let {self.vt_base_field(prim)}: {self.qual(module, pd.module, pd.name)}VTable')
        else:
            out.append(f'    pub let class_info: const {self.qual(module, "ak", "ClassInfo")}*')
        for fn in vi['slots']:
            F = self.p.func_by_usr.get((usr, fn['usr']))
            if F is None:
                continue
            ps = ', '.join([f'{d.name}*'] + [self.R(r, module) for _, r in F.params])
            ret = self.ret_str(F.ret, module, in_type=True)
            out.append(f'    pub let {N.field_name(F.word)}: func({ps}){ret} = {F.name}')
        out.append('')
        # dispatchers
        root = p.root_of(usr)
        rd = p.decls[('rec', root)]
        for fn in vi['slots']:
            F = self.p.func_by_usr.get((usr, fn['usr']))
            if F is None:
                continue
            pnames = self.param_names(F, module, reserve={'this'})
            params = ', '.join([f'this: {d.name}*'] + [f'{n}: {self.R(r, module)}' for n, (_, r) in zip(pnames, F.params)])
            ret = self.ret_str(F.ret, module)
            vt = f'(const {d.name}VTable*)'
            if root == usr:
                access = f'({vt}this.vtable)'
            else:
                access = f'({vt}(({self.qual(module, rd.module, rd.name)}*)this).vtable)'
            call = f'{access}.{N.field_name(F.word)}(' + ', '.join(['this'] + pnames) + ')'
            out.append(f'## Virtual: {fn["q"]}.')
            out.append(f'pub func {F.dispatcher}({params}){ret}:')
            if F.ret.kind == 'fallible':
                if F.ret.inner.kind == 'b' and F.ret.inner.name == 'unit':
                    out.append(f'    try {call}')
                else:
                    out.append(f'    return try {call}')
            elif F.ret.kind == 'b' and F.ret.name == 'unit':
                out.append(f'    {call}')
            else:
                out.append(f'    return {call}')
            out.append('')
            self.stats['dispatchers'] += 1
            self.namemap.append((fn['q'] + ' [dispatch]', module, F.dispatcher, self.loc(d), 'dispatcher'))
        # vtable instance and class info
        s = N.snake(d.name)
        out.append(f'## The vtable of {d.q}.')
        out.append(f'pub let {s}_vtable: {d.name}VTable = {self.vt_init(usr, usr, module)}')
        out.append('')
        ids, shared_with = self.class_id_range(d)
        mixins_arg = ''
        if module == 'web' and p.is_cell(usr):
            mo = self.mixin_offsets(usr)
            if mo:
                parts = []
                for key, (au, fname, bu) in sorted(mo.items()):
                    ad = p.decls[('rec', au)]
                    parts.append(f'{key} = offsetof({self.qual(module, ad.module, ad.name)}, {fname})')
                out.append(f'## Where {d.q}\'s stateful mixins live inside it (DESIGN.md §2.5).')
                out.append(f'pub let {s}_mixins: MixinOffsets = MixinOffsets({", ".join(parts)})')
                out.append('')
                mixins_arg = f', mixins = (const void*)&{s}_mixins'
        if shared_with is not None:
            out.append(f'## Class information of {d.q}: name, the class id of {shared_with} (it shares its nearest')
            out.append('## numbered ancestor\'s id and is recognized by its ClassInfo), size, vtable.')
        else:
            out.append(f'## Class information of {d.q}: name, class-id range (pre-order), size, vtable.')
        out.append(f'pub let {s}_class: {self.qual(module, "ak", "ClassInfo")} = '
                   f'{self.qual(module, "ak", "ClassInfo")}(name = "{d.q.split("::")[-1]}", '
                   f'first_id = {ids[0]}, last_id = {ids[1]}, size = sizeof({d.name}), '
                   f'vtable = (const void*)&{s}_vtable{mixins_arg})')
        out.append('')
        # the vtables of the polymorphic mixins inside this class, with its overrides (§2.5)
        for key, (au, fname, bu) in sorted(self.mixin_offsets(usr).items()):
            if not p.is_poly(bu):
                continue
            md = p.decls[('rec', bu)]
            out.append(f'## The vtable of the {md.q} mixin inside {d.q}.')
            out.append(f'pub let {s}_{key}_vtable: {self.qual(module, md.module, md.name)}VTable = '
                       f'{self.vt_init(usr, bu, module)}')
            out.append('')
            self.stats['mixin_vtables'] += 1
        # is/as helpers over the root interface (a mixin's are the cross-casts of MixinOffsets instead)
        if usr in p.mixin_usrs:
            self.stats['vtables'] += 1
            return out
        iface = self.qual(module, rd.module, 'Is' + rd.name)
        rm = N.snake(rd.name)
        if shared_with is not None:
            classes = [s] + [N.snake(self.p.decls[('rec', u)].name) for u in self.new_descendants(usr)]
            out.append(f'## is<{d.q}>: the cell\'s ClassInfo is its own' +
                       (' or a subclass\'s.' if len(classes) > 1 else '.'))
            out.append(f'pub func is_{s}[P: {iface}](p: P*) -> bool:')
            out.append(f'    let class_info = p.{rm}().vtable.class_info')
            out.append('    return ' + ' or '.join(f'class_info == &{c}_class' for c in classes))
        else:
            out.append(f'## is<{d.q}>: the class-id range test.')
            out.append(f'pub func is_{s}[P: {iface}](p: P*) -> bool:')
            out.append(f'    let id = p.{rm}().class_id')
            out.append(f'    return id >= {s}_class.first_id and id <= {s}_class.last_id')
        out.append('')
        out.append(f'## as_if<{d.q}>.')
        out.append(f'pub func as_if_{s}[P: {iface}](p: P*) -> {d.name}*?:')
        out.append(f'    if is_{s}(p): return ({d.name}*)p')
        out.append('    return none')
        out.append('')
        out.append(f'## as<{d.q}> (verify_cast).')
        out.append(f'pub func as_{s}[P: {iface}](p: P*) -> {d.name}*:')
        out.append(f'    return as_if_{s}(p) else trap("as<{esc(d.q)}> failed")')
        out.append('')
        self.stats['vtables'] += 1
        out += self.creation_helpers(d, module)
        return out

    def class_id_range(self, d):
        """(first, last) class ids of a polymorphic class, and the ancestor whose id it shares (None
        when it has its own range). Against a baseline, a ported class keeps its ids; a new class
        whose hierarchy is numbered shares its nearest numbered ancestor's id (see baseline.py)."""
        usr = d.key[1]
        own = self.p.class_ids.get(usr, (0, 0))
        b = self.baseline
        if b is None or d.module != 'web':
            return own, None
        known = b.class_ids.get(N.snake(d.name) + '_class')
        shared = None
        u = self.p.primary(usr)
        while u is not None and self.p.is_poly(u):
            ad = self.p.decls.get(('rec', u))
            if ad is not None:
                key = N.snake(ad.name) + '_class'
                ids = b.class_ids.get(key if ad.module == 'web' else f'{ad.module}.{key}')
                if ids is not None:
                    shared = ((ids[0], ids[0]), ad.q)
                    break
            u = self.p.primary(u)
        if known is not None:
            # a class a region declared by hand with an ancestor's id (or 0) shares that id
            if shared is not None and (known == shared[0] or known == (0, 0)):
                return shared
            return known, None
        if shared is not None:
            return shared
        return own, None

    def new_descendants(self, usr):
        """The full polymorphic classes below `usr` that the baseline does not number yet."""
        out = []
        for dd in self.p.decls.values():
            if dd.kind != 'record' or dd.level != 'full' or dd.key[1] == usr or not self.p.is_poly(dd.key[1]):
                continue
            if self.class_id_range(dd)[1] is None:
                continue
            u = self.p.primary(dd.key[1])
            while u is not None:
                if u == usr:
                    out.append(dd.key[1])
                    break
                u = self.p.primary(u)
        return sorted(out, key=lambda x: self.p.records[x]['q'])

    def creation_helpers(self, d, module):
        """realm_create_<class> per constructor of a concrete cell class (DESIGN.md §2.3)."""
        p = self.p
        usr = d.key[1]
        r = p.records[usr]
        if module != 'web' or r.get('abstract') or not p.is_cell(usr) or ('rec', self.realm_usr) not in p.decls:
            return []
        out = []
        ctors = [F for F in p.funcs if F.owner_key == d.key and F.kind == 'construct' and F.module == module]
        realm = self.dname(('rec', self.realm_usr), module)
        s = N.snake(d.name)
        for F in ctors:
            suffix = F.word[len('construct'):]
            name = f'realm_create_{s}{suffix}'
            n = 2
            while name in self.module_names[module]:
                name = f'realm_create_{s}{suffix}_{n}'
                n += 1
            self.module_names[module].add(name)
            pnames = self.param_names(F, module, reserve={'this', 'realm'})
            ps = [f'realm: {realm}*'] + [f'{pn}: {"void*?" if has_unmapped(rf) else self.R(rf, module)}'
                                        for pn, (_, rf) in zip(pnames, F.params)]
            args = ', '.join(['this'] + pnames)
            out += [f'## realm.create<{d.q}>(...): allocate under DeferGC, construct, then initialize(realm).',
                    f'pub func {name}({", ".join(ps)}) -> {d.name}*:',
                    f'    let this = ({d.name}*)web_allocate_cell(realm, &{s}_class)',
                    f'    {F.name}({args})',
                    '    web_initialize_cell(this.cell(), realm)',
                    '    return this', '']
            self.namemap.append((f'{d.q} [realm.create]', module, name, self.loc(d), 'creation helper'))
            self.stats['creation_helpers'] += 1
        return out

    def vt_base_field(self, prim_usr):
        return N.snake(self.p.records[prim_usr]['q'].split('::')[-1]) + '_vtable'

    def vt_init(self, cls, level, module):
        p = self.p
        ld = p.decls[('rec', level)]
        parts = []
        prim = p.primary(level)
        if prim is not None and p.is_poly(prim):
            parts.append(f'{self.vt_base_field(prim)} = {self.vt_init(cls, prim, module)}')
        else:
            cd = p.decls[('rec', cls)]
            parts.append(f'class_info = &{self.qual(module, cd.module, N.snake(cd.name) + "_class")}')
        vi = p.vinfo.get(level, {'slots': []})
        for fn in vi['slots']:
            impl = self.resolve_impl(cls, level, fn)
            if impl is None:
                continue
            F = impl
            default = p.func_by_usr.get((level, fn['usr']))
            if default is None or F is default:
                continue
            parts.append(f'{N.field_name(default.word)} = {self.qual(module, F.module, F.name)}')
        return f'{self.qual(module, ld.module, ld.name)}VTable(' + ', '.join(parts) + ')'

    def resolve_impl(self, cls, level, slot_fn):
        p = self.p
        u = cls
        while u is not None:
            vi = p.vinfo.get(u)
            if vi:
                for fn, (iu, ifn) in vi['overrides']:
                    if iu == level and ifn['usr'] == slot_fn['usr']:
                        F = p.func_by_usr.get((u, fn['usr']))
                        if F is not None:
                            return F
            if u == level:
                return p.func_by_usr.get((level, slot_fn['usr']))
            u = p.primary(u)
        return None

