    def emit_enum(self, d, module):
        e = self.p.enums[d.key[1]]
        self.stats['enums'] += 1
        self.namemap.append((self.clean_q(d.q), module, d.name, self.loc(d), 'enum'))
        under = e['under']
        ut = under.get('n') if under.get('k') == 'b' else 'i32'
        ut = {'char': 'i8', 'bool': 'u8', 'u128': 'u64', 'i128': 'i64', 'f32': 'i32', 'f64': 'i64'}.get(ut, ut)
        if ut not in ('u8', 'u16', 'u32', 'u64', 'i8', 'i16', 'i32', 'i64', 'usize', 'isize'):
            ut = 'i32'
        values = [v for _, v in e['cases']]
        if values and min(values) < 0 and ut.startswith('u'):
            ut = 'i64'
        if ut.startswith('u'):
            e_cases = [(n, v & ((1 << {'u8': 8, 'u16': 16, 'u32': 32, 'u64': 64, 'usize': 64}[ut]) - 1)) for n, v in e['cases']]
        else:
            e_cases = e['cases']
        lines = [f'## {self.clean_q(d.q)} ({self.loc(d)}).']
        if not e_cases:
            lines += [f'pub type {d.name} = {ut}', '']
            return lines
        lines.append(f'pub enum {d.name} as {ut}:')
        seen_names = set()
        seen_vals = {}
        aliases = []
        for cname, val in e_cases:
            n = N.safe(N.snake(cname))
            if n == 'none':
                n = 'none_'
            while n in seen_names:
                n += '_'
            if val in seen_vals:
                aliases.append((n, cname, seen_vals[val]))
                continue
            seen_names.add(n)
            seen_vals[val] = n
            lines.append(f'    {n} = {val}')
        lines.append('')
        for n, cname, target in aliases:
            lname = N.safe(N.snake(d.name) + '_' + n)
            lines.append(f'## {d.q}::{cname} (a second name for {target}).')
            lines.append(f'pub let {lname}: {d.name} = {d.name}.{target}')
            self.alias_lets.setdefault(module, set()).add(lname)
        if aliases:
            lines.append('')
        return lines

    def emit_variant(self, d, module):
        info = self.p.variant_info[d.key]
        self.stats['variants'] += 1
        cases = []
        seen = set()
        for it in info['items']:
            if it.kind == 'decl' and self.p.decls[it.key].q == 'AK::Empty':
                n = 'empty'
                payload = None
            else:
                n = N.safe(N.snake(self.nm.short_ref(it)))
                payload = self.R(it, module)
            if n == 'none':
                n = 'none_'
            while n in seen:
                n += '_'
            seen.add(n)
            cases.append(f'    {n}' + (f'(value: {payload})' if payload else ''))
        alias = ', '.join(sorted(info['aliases'])) or 'no alias'
        self.namemap.append(('Variant<' + ', '.join(self.nm.short_ref(i) for i in info['items']) + '>',
                             module, d.name, 'generated', 'variant'))
        return [f'## AK::Variant<...> ({alias}).', f'pub enum {d.name}:'] + cases + ['']

