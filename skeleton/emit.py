    def emit_var(self, v, ref, module):
        name = v['_name']
        self.stats['vars'] += 1
        self.namemap.append((v['q'], module, name, f'{v["file"]}:{v["line"]}', 'variable'))
        init = (v.get('init') or '').replace('\n', ' ')
        if has_unmapped(ref) or not self.visible_ref(ref, module):
            ts = 'void*?'
        else:
            ts = self.R(ref, module)
        lit = literal_value(init, ref)
        lines = [f'## {v["q"]} ({v["file"]}:{v["line"]}).']
        if lit is not None and v.get('constexpr'):
            lines.append(f'pub let {name}: {ts} = {lit}')
        elif lit is not None:
            lines.append(f'pub var {name}: {ts} = {lit}')
        else:
            if init:
                lines.append(f'# C++ initializer: {one_line(init)[:100]}')
            if self.zeroable(ref):
                lines.append(f'pub var {name}: {ts}')
            else:
                ts2 = ts if ts.endswith('?') else (f'({ts})?' if ts.endswith(']') or ts.startswith('func') else ts + '?')
                lines.append(f'pub var {name}: {ts2}  # not zeroable in Luce: optional until initialized')
        lines.append('')
        return lines

    def zeroable(self, ref, depth=0):
        if depth > 20:
            return True
        k = ref.kind
        if k == 'b':
            return True
        if k == 'ptr' or k == 'func':
            return ref.nullable
        if k in ('opt', 'span', 'unmapped'):
            return True
        if k == 'arr':
            return self.zeroable(ref.inner, depth + 1)
        if k == 'tuple':
            return all(self.zeroable(i, depth + 1) for i in ref.items)
        if k == 'decl':
            d = self.p.decls[ref.key]
            if d.kind in ('opaque', 'ovr'):
                return d.name not in ('Function0',) or True
            if d.kind == 'enum':
                e = self.p.enums[d.key[1]]
                return any(v == 0 for _, v in e['cases']) or not e['cases']
            if d.kind == 'variant':
                it = self.p.variant_info[d.key]['items'][0]
                return it.kind == 'decl' and self.p.decls[it.key].q == 'AK::Empty'
            if d.kind in ('record', 'tmpl', 'inst'):
                if d.kind == 'record' and self.p.is_poly(d.key[1]):
                    return False
                for fd, fr in d.info.get('fields', []):
                    if has_unmapped(fr):
                        continue
                    if not self.zeroable(fr, depth + 1):
                        return False
                if d.kind in ('record', 'tmpl'):
                    for role, t, bu in self.p.eff_bases(d.key[1]):
                        if role in ('primary', 'mixin') and not self.zeroable(Ref('decl', key=('rec', bu)), depth + 1):
                            return False
                return True
            return True
        return True

    # ---- functions ------------------------------------------------------------------------------
    def ret_str(self, ret, module, in_type=False):
        if ret.kind == 'b' and ret.name == 'unit':
            return ' -> unit' if in_type else ''
        if has_unmapped(ret):
            return ' -> void*?'
        if in_type and ret.kind == 'fallible' and ret.inner.kind == 'b' and ret.inner.name == 'unit':
            return ' -> unit!'
        return ' -> ' + self.R(ret, module)

    def override_pnames(self, usr):
        """Parameter names of some definition of the virtual `usr` (a pure virtual declared without
        names takes them from an override's definition)."""
        cache = self.__dict__.setdefault('_override_pnames', None)
        if cache is None:
            cache = {}
            for vi in self.p.vinfo.values():
                for fn, (iu, ifn) in vi['overrides']:
                    d = self.p.defs.get(fn['usr'])
                    if d and d.get('pnames') and all(d['pnames']):
                        cache.setdefault(ifn['usr'], d['pnames'])
            self._override_pnames = cache
        return cache.get(usr)

    def param_names(self, F, module, reserve=()):
        d = self.p.defs.get(F.fn['usr'])
        pn = d.get('pnames') if d else None
        if not pn or not all(pn):
            pn = self.override_pnames(F.fn['usr']) or pn
        raw = []
        kept = getattr(F, 'kept', None) or list(range(len(F.params)))
        for i, (n, _) in enumerate(F.params):
            name = ''
            oi = kept[i] if i < len(kept) else i
            if pn and oi < len(pn) and pn[oi]:
                name = pn[oi]
            elif n:
                name = n
            raw.append(name or f'arg{i}')
        out = []
        used = set(reserve)
        forbidden = self.module_names[module]
        for n in raw:
            n = N.safe(n)
            while n in used or n in forbidden or n in S.MODULES:
                n += '_'
            used.add(n)
            out.append(n)
        return out

    def emit_func(self, F, module):
        p = self.p
        fn = F.fn
        self.stats['functions'] += 1
        lines = []
        d = p.defs.get(fn['usr'])
        loc = f'{d["file"]}:{d["line"]}' if d else f'{fn["file"]}:{fn["line"]}'
        what = self.clean_q(fn['q'])
        if F.env_key:
            what = f'{fn["q"]} for {p.decls[F.env_key].name}'
        if getattr(F, 'crtp', False):
            what = f'{self.clean_q(fn["q"])} for {p.decls[F.owner_key].q} (CRTP helper)'
        kind_note = ''
        if F.kind == 'impl':
            kind_note = ' (override)' if F.slot else ' (virtual)'
        lines.append(f'## Ported from {loc} {what}{kind_note}.')
        if F.notes:
            lines.append('# unmapped: ' + one_line('; '.join(F.notes))[:150])
        reserve = {'this', 'base'}
        pnames = self.param_names(F, module, reserve=reserve)
        ps = []
        gen = ''
        if F.generic:
            gen = '[' + ', '.join(F.generic) + ']'
        if F.owner_key and 'static' not in fn.get('flags', []):
            od = p.decls[F.owner_key]
            oname = self.qual(module, od.module, od.name)
            if F.owner_key[0] == 'ovr' and getattr(F, 'owner_args', None):
                oname += '[' + ', '.join(F.owner_args) + ']'
            if F.owner_key[0] == 'tmpl':
                r = p.tmpl_by_usr[F.owner_key[1]]
                tps = [tpn(tp['n']) for tp in r['tparams'] if tp['k'] == 'type']
                if tps:
                    oname += '[' + ', '.join(tps) + ']'
            if F.kind == 'impl':
                if F.slot:
                    iu, _ = F.slot
                    idd = p.decls[('rec', iu)]
                    ps.append(f'base: {self.qual(module, idd.module, idd.name)}*')
                else:
                    ps.append(f'this: {oname}*')
            else:
                poly = p.is_poly_key(F.owner_key)
                const = 'const' in fn.get('flags', []) and not poly and F.kind != 'construct'
                ps.append(f'this: {"const " if const else ""}{oname}*')
        defaults_ok = F.kind != 'impl'
        for i, (n, (_, r)) in enumerate(zip(pnames, F.params)):
            if has_unmapped(r):
                ps.append(f'{n}: void*?')
            else:
                dv = self.default_value(F.defaults[i] if i < len(F.defaults) else None, r, module) \
                    if defaults_ok else None
                ps.append(f'{n}: {self.R(r, module)}' + (f' = {dv}' if dv is not None else ''))
        ret = self.ret_str(F.ret, module)
        pub = 'pub '
        if 'internal' in fn.get('flags', []) and not F.owner_key:
            lines.append('# internal linkage in C++: make it private when it is ported.')
        elif F.owner_key and fn.get('access') == 'private' and F.kind != 'impl':
            # (an unused module-private function is a warning, so the stub stays pub)
            lines.append('# private in C++: make it module-private when it is ported.')
        lines.append(f'{pub}func {F.name}{gen}({", ".join(ps)}){ret}:')
        body = self.trivial_body(F, module, pnames)
        if body is None:
            msg = 'pure virtual' if 'pure' in fn.get('flags', []) else 'unported'
            body = [f'    trap("{msg}: {esc(self.clean_q(fn["q"]))}")']
            self.stats['stubs'] += 1
        else:
            self.stats['trivial'] += 1
        lines += body
        lines.append('')
        self.namemap.append((fn['q'] + (f' [{p.decls[F.env_key].name}]' if F.env_key else ''), module, F.name,
                             loc, F.kind))
        return lines

    def default_value(self, text, ref, module):
        """A C++ default argument as a Luce constant expression, or None."""
        if not text:
            return None
        v = one_line(text)
        if v.startswith('{') and v.endswith('}'):
            inner = v[1:-1].strip()
        else:
            inner = v
        if ref.kind in ('opt',) or (ref.kind in ('ptr', 'func') and ref.nullable):
            if inner in ('', 'nullptr', 'OptionalNone', 'OptionalNone {}', 'OptionalNone { }', '{}', 'NULL'):
                return 'none'
            # `Optional<String> {}`, `Optional<T>()`, `GC::Ptr<T> {}`: the empty value
            if re.fullmatch(r'(?:[\w:]+<.*>|OptionalNone)\s*(?:\{\s*\}|\(\s*\))', inner):
                return 'none'
            if ref.kind == 'opt':
                return self.default_value(text, ref.inner, module)
            return None
        lit = literal_value(v, ref)
        if lit is not None:
            return lit
        if ref.kind == 'b' and ref.name == 'bool' and inner in ('true', 'false'):
            return inner
        if ref.kind == 'decl' and ref.key[0] == 'enum':
            case = self.enum_case(ref.key, inner)
            if case is not None:
                return f'{self.dname(ref.key, module)}.{case[0]}'
        if ref.kind == 'decl' and ref.key[0] == 'variant' and re.fullmatch(r'(?:[\w:]+(?:<.*>)?\s*)?(?:\{\s*\}|\(\s*\))|Empty\s*\{\s*\}', inner):
            # a default-constructed Variant<Empty, ...> holds Empty
            first = self.p.variant_info[ref.key]['items'][0]
            if first.kind == 'decl' and self.p.decls[first.key].q == 'AK::Empty':
                return f'{self.dname(ref.key, module)}.empty'
        return None

    def trivial_body(self, F, module, pnames):
        d = self.p.defs.get(F.fn['usr'])
        if not d or 'body' not in d or 'pure' in F.fn.get('flags', []):
            return None
        toks = d['body']
        ret = F.ret
        if F.kind == 'construct':
            return None  # a constructor's mem-initializers are not in its body
        if toks == ['{', '}']:
            if ret.kind == 'b' and ret.name == 'unit':
                return ['    return']
            if ret.kind == 'fallible' and ret.inner.kind == 'b' and ret.inner.name == 'unit':
                return ['    return']
            return None
        if len(toks) == 5 and toks[0] == '{' and toks[1] == 'return' and toks[3] == ';' and toks[4] == '}':
            v = toks[2]
            if v in ('true', 'false') and ret.kind == 'b' and ret.name == 'bool':
                return [f'    return {v}']
            if v == 'nullptr' and ret.kind in ('ptr', 'opt') and (ret.nullable or ret.kind == 'opt'):
                return ['    return none']
            if re.fullmatch(r'\d+', v) and ret.kind == 'b' and ret.name in ('u8', 'u16', 'u32', 'u64', 'i8', 'i16',
                                                                          'i32', 'i64', 'usize', 'isize'):
                return [f'    return {v}']
            if re.fullmatch(r'm_\w+', v) and F.owner_key and F.kind not in ('impl', 'construct') and \
                    F.owner_key[0] == 'rec' and 'static' not in F.fn.get('flags', []):
                od = self.p.decls[F.owner_key]
                for fd, fr in od.info.get('fields', []):
                    if fd['n'] == v and not has_unmapped(fr) and self.visible_ref(fr, od.module) and \
                            self.R(fr, module) == self.R(ret, module) and ret.kind != 'fallible':
                        return [f'    return this.{v}']
        return None

    # ---- output ---------------------------------------------------------------------------------
    def write_module(self, module, frags):
        # The flat package layout: a package's modules live directly under src/ (src/<module>/).
        mdir = os.path.join(self.out, 'src', module)
        os.makedirs(mdir, exist_ok=True)
        order = ['module.lucb']
        support = self.support.get(module)
        if support:
            order.append('support.lucb')
        rels = sorted(frags.keys(), key=lambda r: (
            0 if '/types_' in '/' + r and 'variants' not in r and 'traits' not in r else
            1 if 'variants' in r or 'traits' in r else 2, r))
        bodies = {}
        for rel in rels:
            f = frags[rel]
            f['blocks'].sort(key=lambda b: b[0])
            content = []
            for _, lines in f['blocks']:
                content += lines
            files = sorted(f['files'])
            desc = f['desc']
            if desc is None:
                if rel.split('/')[-1].startswith('stub_'):
                    desc = wrap_desc('Every function of the region with its generated signature and a '
                                     '`trap("unported: ...")` body, in the donor files\' order (DESIGN.md '
                                     '§4.5). A region agent replaces this fragment with ported fragments and '
                                     'deletes it. Generated by the skeleton generator from Ladybird at '
                                     f'{PIN}; do not edit by hand.')
                    desc += [''] + ['Donor files:'] + ['    ' + x for x in files[:40]]
                    if len(files) > 40:
                        desc.append(f'    ... and {len(files) - 40} more')
                else:
                    desc = wrap_desc('Structs, enums, vtables, class information and cast helpers generated '
                                     'from ' + ', '.join(files[:6]) + (' and more' if len(files) > 6 else '') +
                                     f' (Ladybird {PIN}) by the skeleton generator (DESIGN.md §4.4). '
                                     'Regenerate rather than edit, except to fill a field the generator '
                                     'could not map.')
            text = header_box(f['title'], desc) + content
            bodies[rel] = text
            order.append(rel)
        imports = self.import_lines(module)
        mdesc = wrap_desc(MODULE_DESC.get(module, module)) + [''] + LICENSE_LINES
        mtext = header_box(f'{module} - {MODULE_TITLE.get(module, module)}', mdesc) + imports + ['']
        self.write(os.path.join(mdir, 'module.lucb'), mtext)
        if support:
            self.write(os.path.join(mdir, 'support.lucb'), support)
        for rel, text in bodies.items():
            path = os.path.join(mdir, rel)
            os.makedirs(os.path.dirname(path), exist_ok=True)
            self.write(path, text)
        self.write(os.path.join(mdir, 'ORDER'), order)

    def import_lines(self, module):
        """module.lucb's imports: the standard modules by name, a module of this package by its short
        name, another package's modules as from-imports grouped per package (`from
        luce_browser_foundation import ak, gc`)."""
        lines = sorted(f'import {m}' for m in self.extra_imports.get(module, ()))
        foreign = collections.OrderedDict()
        for m in S.MODULES:
            if m not in self.refs_used[module] or m == module:
                continue
            if S.PACKAGE_OF[m] == self.package:
                lines.append(f'import {m}')
            else:
                foreign.setdefault(PACKAGE_ROOT[S.PACKAGE_OF[m]], []).append(m)
        for root, mods in foreign.items():
            lines.append(f'from {root} import {", ".join(mods)}')
        return lines

    def write(self, path, lines):
        text = '\n'.join(lines).rstrip('\n') + '\n'
        text = re.sub(r'\n{3,}', '\n\n', text)
        with open(path, 'w') as f:
            f.write(text)
        self.stats['lines'] += text.count('\n')


